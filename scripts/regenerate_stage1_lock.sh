#!/usr/bin/env bash
# Generate and verify the target-platform lock. This script intentionally does
# not bootstrap pip-tools over the network: run it only in an approved builder
# image/environment where pip-tools is already provisioned and fingerprinted.
set -euo pipefail
IFS=$'\n\t'

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
INPUT="${ROOT}/requirements-stage1.in"
OUTPUT="${ROOT}/requirements-stage1.lock"
PYTHON_BIN="${PYTHON_BIN:-python3.12}"

fail() { printf 'FAIL: %s\n' "$*" >&2; exit 1; }

[[ -f "${INPUT}" ]] || fail "Missing input file: ${INPUT}"
grep -Fqx 'jsonschema[format-nongpl]==4.23.0' "${INPUT}" || fail "requirements-stage1.in must pin jsonschema[format-nongpl]==4.23.0."
command -v "${PYTHON_BIN}" >/dev/null 2>&1 || fail "${PYTHON_BIN} is required; lock must be compiled for CPython 3.12."

PY_VERSION="$(${PYTHON_BIN} -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')"
[[ "${PY_VERSION}" == "3.12" ]] || fail "Expected CPython 3.12; found ${PY_VERSION}."
PIPTOOLS_VERSION="$(${PYTHON_BIN} -c 'import importlib.metadata; print(importlib.metadata.version("pip-tools"))' 2>/dev/null)" || fail "pip-tools must be pre-provisioned into ${PYTHON_BIN}; no unpinned bootstrap is permitted."
[[ "${PIPTOOLS_VERSION}" == "7.4.1" ]] || fail "Expected approved pip-tools 7.4.1, found ${PIPTOOLS_VERSION}."
printf 'LOCK BUILDER: python=%s pip-tools=%s platform=%s\n' "${PY_VERSION}" "${PIPTOOLS_VERSION}" "$(uname -srm)"

TMP_LOCK="$(mktemp "${ROOT}/.requirements-stage1.lock.XXXXXX")"
TMP_ENV="$(mktemp -d "${ROOT}/.stage1-lock-verify.XXXXXX")"
cleanup() { rm -f -- "${TMP_LOCK}"; rm -rf -- "${TMP_ENV}"; }
trap cleanup EXIT

# --upgrade forces a fresh resolution; all hashes are emitted by pip-compile
# from the configured package index metadata rather than hand-entered.
CUSTOM_COMPILE_COMMAND="./scripts/regenerate_stage1_lock.sh" \
  "${PYTHON_BIN}" -m piptools compile \
    --upgrade \
    --generate-hashes \
    --resolver=backtracking \
    --strip-extras \
    --output-file "${TMP_LOCK}" \
    "${INPUT}"

grep -Fq 'autogenerated by pip-compile' "${TMP_LOCK}" || fail "Generated output lacks pip-compile provenance header."
grep -Eq '^jsonschema==4\.23\.0([[:space:]\\]|$)' "${TMP_LOCK}" || fail "Generated lock does not pin jsonschema==4.23.0."
grep -Eq '^rpds-py==' "${TMP_LOCK}" || fail "Generated lock omits rpds-py."

"${PYTHON_BIN}" -m venv "${TMP_ENV}/venv"
# All transitive dependencies are explicit lock entries; --no-deps prevents
# pip from resolving any additional unpinned package during installation.
"${TMP_ENV}/venv/bin/python" -m pip install --require-hashes --no-deps -r "${TMP_LOCK}"
"${TMP_ENV}/venv/bin/python" -m pip check
"${TMP_ENV}/venv/bin/python" - <<'PY'
import importlib.metadata
from jsonschema import FormatChecker
from jsonschema.exceptions import FormatError

required = {
    "jsonschema", "attrs", "jsonschema-specifications", "referencing", "rpds-py",
    "fqdn", "idna", "isoduration", "arrow", "python-dateutil", "six", "tzdata",
    "jsonpointer", "rfc3339-validator", "rfc3986-validator", "uri-template", "webcolors",
}
installed = {d.metadata["Name"].lower().replace("_", "-") for d in importlib.metadata.distributions() if d.metadata.get("Name")}
missing = sorted(required - installed)
if missing:
    raise SystemExit(f"missing required distributions: {missing}")
checker = FormatChecker()
checker.check("2026-10-15T21:03:21Z", "date-time")
try:
    checker.check("2026-10-15T21:03:21", "date-time")
except FormatError:
    pass
else:
    raise SystemExit("FormatChecker did not reject date-time without timezone")
print("LOCK_VERIFY_PASS: required graph installed, pip check clean, date-time checker active")
PY

# Replace existing output only after compilation, hash-checked installation,
# complete dependency check, and FormatChecker negative test all succeed.
mv -- "${TMP_LOCK}" "${OUTPUT}"
printf 'LOCK_GENERATION_PASS: %s\n' "${OUTPUT}"
